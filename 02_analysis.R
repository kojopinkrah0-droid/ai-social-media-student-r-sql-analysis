library(readr)
library(dplyr)
library(ggplot2)
s <- read_csv("data/processed/student_wellbeing_clean.csv",show_col_types=FALSE)
num <- s %>% select(Age,Daily_Social_Media_Hours,Daily_AI_Tool_Usage_Hours,Sleep_Hours,Physical_Activity_Hours,Mental_Health_Score,Physical_Health_Score)
write.csv(round(cor(num),3),"results/r_correlation_matrix.csv")
write_csv(s %>% summarise(across(where(is.numeric),mean)),"results/r_numeric_means.csv")
social <- s %>% group_by(Social_Media_Band) %>% summarise(n=n(),mental=mean(Mental_Health_Score),physical=mean(Physical_Health_Score),.groups="drop")
write_csv(social,"results/r_social_media_summary.csv")
p1 <- ggplot(social,aes(Social_Media_Band,mental))+geom_col()+theme_minimal()+labs(title="Mental Health by Social Media Use",x="Daily social media",y="Average mental health")
ggsave("images/r_mental_health_by_social_media.png",p1,width=8,height=5,dpi=150)
p2 <- ggplot(s,aes(Daily_Social_Media_Hours,Mental_Health_Score))+geom_point(alpha=.15)+geom_smooth(method="lm",se=FALSE)+theme_minimal()+labs(title="Social Media Use and Mental Health")
ggsave("images/r_social_vs_mental.png",p2,width=8,height=5,dpi=150)
p3 <- ggplot(s,aes(Sleep_Hours,Mental_Health_Score))+geom_point(alpha=.15)+geom_smooth(method="lm",se=FALSE)+theme_minimal()+labs(title="Sleep and Mental Health")
ggsave("images/r_sleep_vs_mental.png",p3,width=8,height=5,dpi=150)
p4 <- ggplot(s,aes(Physical_Activity_Hours,Physical_Health_Score))+geom_point(alpha=.15)+geom_smooth(method="lm",se=FALSE)+theme_minimal()+labs(title="Physical Activity and Physical Health")
ggsave("images/r_activity_vs_physical.png",p4,width=8,height=5,dpi=150)
